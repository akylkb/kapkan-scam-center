/** Луч вправо: нечётное число пересечений — точка внутри */
function inside(lon: number, lat: number, ring: Ring): boolean {
  let hit = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      hit = !hit;
    }
  }
  return hit;
}

function sample(): [number, number][] {
  const dots: [number, number][] = [];
  // Шаг 2.4° даёт ~1600 точек: карта читается, а SVG остаётся лёгким
  for (let lon = -178; lon <= 180; lon += 2.4) {
    for (let lat = -56; lat <= 78; lat += 2.4) {
      if (LAND.some((ring) => inside(lon, lat, ring))) {
        dots.push([lon, lat]);
      }
    }
  }
  return dots;
}

export const WORLD_DOTS: readonly (readonly [number, number])[] = sample();
