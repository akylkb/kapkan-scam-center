/**
 * Протокол живого слоя: что экраны говорят друг другу во время дубля.
 *
 * Здесь только типы и константы — ни сети, ни логики. Файл читают и клиент
 * (lib/live/bus.ts), и съёмочный сервер (scripts/serve.mjs), поэтому он должен
 * оставаться описанием формата, а не реализацией.
 *
 * Почему не WebSocket. Серверного рантайма у проекта нет (output: 'export'),
 * а ws — это лишняя npm-зависимость, которой на площадке может не оказаться.
 * Задача при этом асимметрична и раскладывается на два готовых примитива:
 * приём — SSE (EventSource сам переподключается), отправка — обычный POST
 * («выстрелил и забыл», ответ не нужен). Оба живут на голом node:http внутри
 * того же сервера, что раздаёт страницы, — ноль зависимостей.
 */
import type { Attach } from "@/lib/fixtures/threads";
import type { SceneEventKind } from "@/lib/scene/events";

/** Единственный сетевой адрес во всём проекте — и тот на своём же origin */
export const LIVE_PATH = "/live";

/** Имя вкладочной шины. Одно на все экраны: комната лежит в конверте */
export const LIVE_CHANNEL = "kapkan-live";

/**
 * Комнаты.
 *
 * `seat-N` — переписка конкретного рабочего места: чатер и телефон жертвы.
 * `scene` — команды режиссёра, они общие для всех экранов независимо от места
 * (раньше это делал BroadcastChannel("kapkan-scene"): Ctrl+Alt+2 на /chat/3
 * должен вспыхнуть и на /wall).
 */
export const SCENE_ROOM = "scene";
export type LiveRoom = typeof SCENE_ROOM | `seat-${number}`;

/** Кто написал реплику. Совпадает с Message["from"], кроме служебного system */
export type LiveSide = "victim" | "operator";

export type LiveMessage =
  /** Реплика, напечатанная актёром в кадре */
  | { t: "say"; from: LiveSide; threadId: string; text: string; attach?: Attach }
  /**
   * Реплику убрали из переписки. Летит по той же комнате, что и say, поэтому
   * гаснет сразу на обоих экранах — и у чатера, и на телефоне жертвы.
   *
   * Удаляется по id, а не по содержимому: id есть и у фикстурной реплики,
   * и у живой, так что стереть можно любую, включая заготовленную историю.
   * Сообщение остаётся в журнале сервера — иначе F5 посреди дубля воскресил
   * бы стёртую реплику вместе с остальной перепиской.
   */
  | { t: "unsay"; threadId: string; msgId: string }
  /** «Печатает…». Гаснет само по TYPING_TTL_MS, отдельного выключения не ждём */
  | { t: "typing"; from: LiveSide; threadId: string }
  /** Чатер объявил открытый диалог — телефон жертвы следует за ним */
  | { t: "focus"; threadId: string; personaId: string }
  /**
   * Команда режиссёра — чтобы Ctrl+Alt+… долетал до соседней машины.
   *
   * Сюда же уходит тап жертвы по фишинговой ссылке: телефон шлёт обычный
   * "link.opened", тот самый, что висит на Ctrl+Alt+9. Отдельного типа для
   * тапа нет намеренно — иначе у одного события было бы два разных пути,
   * и живой тап однажды разошёлся бы с хоткеем.
   */
  | { t: "scene"; kind: SceneEventKind };

/**
 * Конверт. `id` присваивает отправитель: по нему шина отбрасывает дубли
 * (сообщение приходит и по вкладочному каналу, и по сети) и узнаёт эхо
 * собственной реплики — оно же служит подтверждением доставки.
 *
 * `seq` проставляет сервер: сквозной номер для догона после разрыва.
 */
export type LiveEnvelope = {
  id: string;
  room: LiveRoom;
  msg: LiveMessage;
  seq?: number;
};

/** Куда идёт сообщение: команды режиссёра — общие, остальное — по месту */
export function roomFor(msg: LiveMessage, seat: number): LiveRoom {
  return msg.t === "scene" ? SCENE_ROOM : `seat-${seat}`;
}

/** Сколько «печатает…» держится на экране после последней нажатой клавиши */
export const TYPING_TTL_MS = 3_000;

/** Как часто отправитель повторяет «печатает…», пока актёр набирает текст */
export const TYPING_THROTTLE_MS = 1_200;

/** Состояние моста — показывается тусклой строкой вне кадра */
export type LiveStatus =
  /** Сеть: экраны связаны через съёмочный сервер, работают разные машины */
  | "net"
  /** Только вкладки этой машины (npm run dev или сервер без моста) */
  | "tabs"
  /** Связи нет вообще: браузер без BroadcastChannel */
  | "off";

export const LIVE_STATUS_LABEL: Record<LiveStatus, string> = {
  net: "мост · сеть",
  tabs: "мост · вкладки",
  off: "мост · нет",
};
